"""Generate src/android/turnip_supported.h from Mesa's freedreno_devices.py at the bundled Turnip revision.

Usage: python tools/turnip/gen_supported.py <freedreno_devices.py>
Only A6xx-A8xx entries are kept: Turnip rejects other generations (tu_device.cc).
"""
from pathlib import Path
import hashlib
import re
import sys

MESA = '02f13375231bf0a9ed20b09cb21171351053be52'
SHA256 = '6b7fd9f919cc84bade096292f3cb5f8c73d5d479096d3a4a4e2fbac1e0b29952'
OUT = Path(__file__).resolve().parents[2] / 'src/android/turnip_supported.h'


def entries(src):
    blocks = re.findall(r'add_gpus\(\[(.*?)\],\s*\w*GPUInfo\(\s*(?:chip\s*=\s*)?CHIP\.A(\d)XX', src, re.S)
    assert len(blocks) == src.count('\nadd_gpus('), 'unparsed add_gpus block'
    out = []
    for ids, gen in blocks:
        if int(gen) < 6:
            continue
        for args in re.findall(r'GPUId\(([^)]*)\)', ids):
            chip = re.search(r'chip_id\s*=\s*(0x[0-9a-fA-F]+)', args)
            gpu = 0 if chip else int(re.match(r'\s*(\d+)', args).group(1))
            if not chip:  # GPUId(gpu_id): Mesa's wildcard patch form
                chip_id = (gpu // 100 << 24) | (gpu // 10 % 10 << 16) | (gpu % 10 << 8) | 0xff
            else:
                chip_id = int(chip.group(1), 16)
            out.append((gpu, chip_id))
    return out


def main(path):
    data = Path(path).read_bytes()
    if hashlib.sha256(data).hexdigest() != SHA256:
        raise SystemExit('freedreno_devices.py is not the pinned Mesa revision')
    rows = entries(data.decode())
    lines = ['// Generated by tools/turnip/gen_supported.py from Mesa ' + MESA,
             '// src/freedreno/common/freedreno_devices.py (A6xx-A8xx). Do not edit.',
             '#pragma once', '#include <cstdint>', '',
             'struct TurnipDevice { uint32_t gpu_id; uint64_t chip_id; };',
             'inline constexpr TurnipDevice kTurnipDevices[] = {']
    lines += [f'    {{{g}, 0x{c:x}ull}},' for g, c in rows]
    lines += ['};', '']
    OUT.write_text('\n'.join(lines), newline='\n')
    print(f'{len(rows)} entries -> {OUT}')


if __name__ == '__main__':
    main(sys.argv[1])
